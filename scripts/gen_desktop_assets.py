#!/usr/bin/env python3
"""Generate app/desktop/assets_gen.{c,h} from a Momentum-Firmware checkout.

Copies a few u8g2 fonts (raw u8g2 format, decoded at runtime by gfx.c) and
converts Flipper 1-bit PNG icons into packed bitmaps, so the desktop shell
uses the same type and iconography as the Flipper itself.

Usage: scripts/gen_desktop_assets.py <path-to-Momentum-Firmware>

The output is committed, so building the VGM firmware never needs the
Momentum tree; rerun this only when the font/icon list changes.
"""
import re
import sys
from pathlib import Path

from PIL import Image

FONTS = [
    # (u8g2 name, C name)
    ("haxrcorp4089_tr", "font_secondary"),  # Flipper FontSecondary
    ("helvB08_tr", "font_primary"),  # Flipper FontPrimary (bold)
    ("profont11_mr", "font_mono"),  # Flipper FontKeyboard
    ("profont22_tn", "font_big_numbers"),  # Flipper FontBigNumbers
    ("4x6_tr", "font_tiny"),
    ("helvB10_tr", "font_title"),
]

ICONS = [
    # (path under assets/icons, C name)
    ("Archive/dir_10px.png", "icon_dir"),
    ("Archive/file_10px.png", "icon_file"),
    ("Archive/unknown_10px.png", "icon_unknown"),
    ("Archive/sub1_10px.png", "icon_subghz"),
    ("Archive/Nfc_10px.png", "icon_nfc"),
    ("Archive/125_10px.png", "icon_rfid"),
    ("Archive/ir_10px.png", "icon_ir"),
    ("Archive/ibutt_10px.png", "icon_ibutton"),
    ("Archive/badusb_10px.png", "icon_badusb"),
    ("Archive/u2f_10px.png", "icon_u2f"),
    ("Archive/Apps_10px.png", "icon_apps"),
    ("Archive/js_script_10px.png", "icon_js"),
    ("Archive/music_10px.png", "icon_music"),
    ("Archive/settings_10px.png", "icon_settings"),
    ("Archive/back_10px.png", "icon_back"),
    ("Archive/keyboard_10px.png", "icon_keyboard"),
    ("Archive/search_10px.png", "icon_search"),
    ("StatusBar/SDcardMounted_11x8.png", "icon_sd"),
    ("StatusBar/Battery_25x8.png", "icon_battery"),
    ("StatusBar/Charging_lightning_9x10.png", "icon_charging"),
    ("StatusBar/Exp_module_connected_12x8.png", "icon_expansion"),
]


def parse_c_string_literals(text):
    """Concatenate adjacent C string literals and decode their escapes."""
    out = bytearray()
    for lit in re.findall(r'"((?:[^"\\]|\\.)*)"', text, re.S):
        i = 0
        while i < len(lit):
            c = lit[i]
            if c != "\\":
                out.append(ord(c))
                i += 1
                continue
            n = lit[i + 1]
            if n in "01234567":
                m = re.match(r"[0-7]{1,3}", lit[i + 1 :])
                out.append(int(m.group(0), 8))
                i += 1 + len(m.group(0))
            elif n == "x":
                m = re.match(r"[0-9a-fA-F]+", lit[i + 2 :])
                out.append(int(m.group(0), 16) & 0xFF)
                i += 2 + len(m.group(0))
            else:
                out.append({"n": 10, "t": 9, "r": 13, "\\": 92, '"': 34, "'": 39, "?": 63}[n])
                i += 2
    return bytes(out)


def extract_font(src, name):
    m = re.search(
        r"const uint8_t u8g2_font_%s\[(\d+)\][^=]*=(.*?);\s*$" % re.escape(name), src, re.S | re.M
    )
    if not m:
        sys.exit(f"font {name} not found")
    size = int(m.group(1))
    data = parse_c_string_literals(m.group(2))
    # The declared array size includes the string's terminating NUL.
    data = data + b"\0"
    if len(data) != size:
        sys.exit(f"font {name}: parsed {len(data)} bytes, expected {size}")
    return data


def load_icon(path):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    stride = (w + 7) // 8
    data = bytearray(stride * h)
    for y in range(h):
        for x in range(w):
            r, g, b, a = im.getpixel((x, y))
            if a > 127 and r + g + b < 384:  # black pixel = "on" on the Flipper LCD
                data[y * stride + x // 8] |= 0x80 >> (x % 8)
    return w, h, bytes(data)


def c_bytes(data, indent="    "):
    lines = []
    for i in range(0, len(data), 16):
        lines.append(indent + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ",")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    momentum = Path(sys.argv[1])
    out_dir = Path(__file__).resolve().parent.parent / "app" / "desktop"
    src = (momentum / "lib/u8g2/u8g2_fonts.c").read_text(errors="replace")

    c = [
        "/* Generated by scripts/gen_desktop_assets.py from Momentum-Firmware; do not edit. */",
        '#include "assets_gen.h"',
        "",
    ]
    h = [
        "/* Generated by scripts/gen_desktop_assets.py; do not edit. */",
        "#pragma once",
        '#include "gfx.h"',
        "",
    ]
    for u8name, cname in FONTS:
        data = extract_font(src, u8name)
        c.append(f"/* u8g2_font_{u8name} */")
        c.append(f"const uint8_t {cname}[{len(data)}] = {{")
        c.append(c_bytes(data))
        c.append("};")
        c.append("")
        h.append(f"extern const uint8_t {cname}[{len(data)}]; /* u8g2_font_{u8name} */")
    h.append("")
    for rel, cname in ICONS:
        w, hh, data = load_icon(momentum / "assets/icons" / rel)
        c.append(f"/* {rel} */")
        c.append(f"static const uint8_t {cname}_data[] = {{")
        c.append(c_bytes(data))
        c.append("};")
        c.append(f"const gfx_icon_t {cname} = {{{w}, {hh}, {cname}_data}};")
        c.append("")
        h.append(f"extern const gfx_icon_t {cname}; /* {w}x{hh} */")
    (out_dir / "assets_gen.c").write_text("\n".join(c) + "\n")
    (out_dir / "assets_gen.h").write_text("\n".join(h) + "\n")
    print(f"wrote {out_dir}/assets_gen.{{c,h}}: {len(FONTS)} fonts, {len(ICONS)} icons")


if __name__ == "__main__":
    main()
